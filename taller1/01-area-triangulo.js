// fómula: AT = (B * H) / 2
// AT = Área del triángulo
// B = Base
// H = Altura
// =========================

// Cambiar estos Valores para probar el programa con otros datos

const base = 10; //Base del triángulo (numero)
const altura = 4; // altura del triángulo (número)

// Aplicamos la fórmula del área : (base por altura dividido entre 2).
const areaTriangulo = (base * altura) / 2;

//mostrar en consola los datos  de entrada junto el resultado obtenido.
console.log ("==== ÁREA DE UN TRIÁNGULO");
console.log ("La base es: " , base); // Imprime el valor de la base.
console.log ("La altura es:", altura); // Imprime el valor de la altura.
console.log ("El àrea del triángulo es:" , areaTriangulo); // Imprime el resultado final.
